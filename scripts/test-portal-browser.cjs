const assert = require('node:assert/strict');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2] || 'http://127.0.0.1:8892';
const live = base.startsWith('https:');
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const context = await browser.newContext();
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror',error=>errors.push(error.message));
    if (!live) await context.route('https://zgland.com/assets/js/site-tools*.js*',route=>route.fulfill({path:path.resolve(__dirname,'../assets/js/site-tools.js'),contentType:'application/javascript'}));
    for (const width of [1360,390]) {
      await page.setViewportSize({width,height:900});
      assert.equal((await page.goto(base+'/?qa=portal')).status(),200);
      await page.waitForFunction(()=>document.getElementById('siteCount').textContent.includes('12'));
      assert.equal(await page.locator('.site-card:visible').count(),12);
      await page.locator('#siteSearch').fill('创投');
      assert.equal(await page.locator('.site-card:visible').count(),1);
      await page.locator('#siteSearch').press('Escape');
      await page.locator('[data-filter=research]').click();
      assert.equal(await page.locator('.site-card:visible').count(),4);
      await page.locator('#siteSearch').fill('not-found-qa');
      assert.equal(await page.locator('#emptySites').isVisible(),true);
      await page.locator('#siteSearch').fill('');
      await page.locator('[data-filter=all]').click();
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
      if (process.env.QA_SCREENSHOT_DIR) await page.screenshot({path:path.join(process.env.QA_SCREENSHOT_DIR,`portal-${live?'live':'local'}-${width}.png`),fullPage:true});
      const companyUrl = live ? 'https://hzct.zgland.com/' : base+'/company-home.html';
      assert.equal((await page.goto(companyUrl)).status(),200);
      assert((await page.title()).includes('杭州创投'));
      assert.equal(await page.locator('.work-evidence-grid img, .work-evidence img').count()>0 || await page.getByText('创投作品1 · 协拍人员',{exact:true}).count()>0,true);
      assert.equal(await page.getByText('量化研究与重点新闻',{exact:true}).count(),0);
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
      const companyImages = await page.locator('img[src*="chuangtou-work-"]').evaluateAll(images=>images.map(image=>image.getAttribute('src')));
      assert.equal(companyImages.length,2);
    }
    let probes=0;
    await page.route('**/api/quant-status', async route=>{
      probes++;
      await new Promise(resolve=>setTimeout(resolve,120));
      await route.fulfill({contentType:'application/json',body:JSON.stringify({state:'protected',title:'入口可达，认证保护生效',message:'仅检查登录挑战',checkedAt:new Date().toISOString()})});
    });
    await page.goto(base+'/quant-console/');
    await page.evaluate(()=>window.open=()=>({opener:null,closed:false,document:{body:{}},location:{replace(){}},close(){this.closed=true}}));
    assert.equal(probes,0);
    await page.locator('#enterCloud').click();
    assert.equal(await page.locator('#enterCloud').getAttribute('aria-disabled'),'true');
    await page.waitForFunction(()=>document.querySelector('#cloudStatus').dataset.state==='protected');
    assert.equal(probes,1);
    assert.equal(await page.locator('#wakeCloud').isVisible(),false);
    assert.equal(await page.locator('#enterCloud').getAttribute('href'),'/api/quant-enter');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
    await page.unroute('**/api/quant-status');
    await page.route('**/api/quant-status',route=>route.abort());
    await page.locator('#enterCloud').click();
    await page.waitForFunction(()=>document.querySelector('#statusTitle').textContent==='本次检查未完成');
    assert.equal(await page.locator('#enterCloud').getAttribute('aria-disabled'),null);
    assert.equal(await page.locator('#wakeCloud').isVisible(),true);
    const sent=[];
    page.on('request',request=>{if(['POST','PUT','PATCH'].includes(request.method()))sent.push(request.url())});
    const sample={exported_at:'2026-10-19T12:00:00',strategies:{demo:{kind:'balanced',fast_ma:10,slow_ma:40}},portfolio:{holdings:[],journal:[]}};
    await page.locator('#backupFile').setInputFiles({name:'state.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(sample))});
    await page.waitForFunction(()=>document.querySelector('#backupResult').textContent.includes('结构初检通过'));
    assert((await page.locator('#backupResult').innerText()).includes('不含行情'));
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
    await page.locator('#clearBackup').click();
    assert((await page.locator('#backupResult').innerText()).includes('尚未选择'));
    await page.locator('#backupFile').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"private-note":"DO_NOT_RENDER"}')});
    await page.waitForFunction(()=>document.querySelector('#backupResult').dataset.state==='unavailable');
    assert(!(await page.locator('#backupResult').innerText()).includes('DO_NOT_RENDER'));
    assert.deepEqual(sent,[]);
    assert.deepEqual(errors,[]);
    await context.close();
    console.log('PASS: portal search/category/empty/reset, distinct company content, desktop/mobile layout, bounded status, local backup check/clear/error, no backup uploads or automatic probes.');
  } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1});
